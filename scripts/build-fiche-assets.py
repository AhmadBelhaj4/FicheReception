#!/usr/bin/env python3
"""Generates the embedded assets used by the PDF template (src/utils/fichePdf.ts).

Outputs
  src/assets/ficheFonts.ts      subset fonts as base64 @font-face CSS
  src/assets/ficheMetrics.ts    glyph advance widths (for shrink-to-fit decisions)
  src/assets/defaultLogos.ts    default ENNOUR logos as data URIs

Fonts: Liberation Serif (metric-compatible with Times New Roman) and Carlito
(metric-compatible with Calibri), both SIL Open Font License 1.1. Embedding them
makes the PDF render identically on every device instead of falling back to the
phone's default serif font.

Usage: python3 scripts/build-fiche-assets.py <logos_dir>
  <logos_dir> must contain arru.png, samed.png, soit.png
"""
import base64, io, json, sys, tempfile, os
from fontTools import subset
from fontTools.ttLib import TTFont
from PIL import Image

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "assets")
# metrics key -> (css family, file, weight)
FONTS = {
    "FicheSerif":     ("FicheSerif", "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf", 400),
    "FicheSerifBold": ("FicheSerif", "/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf", 700),
    "FicheSans":      ("FicheSans",  "/usr/share/fonts/truetype/crosextra/Carlito-Regular.ttf", 400),
}
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x20AC, 0x0152, 0x0153]

def subset_font(path, flavor):
    opts = subset.Options(); opts.flavor = flavor; opts.layout_features = ["kern", "liga"]
    opts.name_IDs = [1, 2, 4, 6]; opts.notdef_outline = True
    f = TTFont(path)
    s = subset.Subsetter(opts); s.populate(unicodes=UNICODES); s.subset(f)
    buf = io.BytesIO(); f.flavor = flavor; f.save(buf); return buf.getvalue()

try:
    import brotli  # noqa: F401
    flavor, mime, fmt = "woff2", "font/woff2", "woff2"
except ImportError:
    flavor, mime, fmt = "woff", "font/woff", "woff"

css, metrics = [], {}
for key, (fam, path, weight) in FONTS.items():
    b64 = base64.b64encode(subset_font(path, flavor)).decode()
    css.append(f"@font-face{{font-family:'{fam}';font-weight:{weight};font-style:normal;"
               f"src:url(data:{mime};base64,{b64}) format('{fmt}');}}")
    f = TTFont(path); upm = f["head"].unitsPerEm; cmap = f.getBestCmap(); hmtx = f["hmtx"]
    metrics[key] = {chr(u): round(hmtx[cmap[u]][0] / upm, 4) for u in UNICODES if u in cmap}

hdr = "// AUTO-GENERATED by scripts/build-fiche-assets.py — do not edit by hand.\n"
with open(os.path.join(OUT, "ficheFonts.ts"), "w") as fh:
    fh.write(hdr + "// Liberation Serif + Carlito (SIL OFL 1.1), Latin subset.\n")
    fh.write("export const FICHE_FONT_CSS = " + json.dumps("\n".join(css)) + ";\n")
with open(os.path.join(OUT, "ficheMetrics.ts"), "w") as fh:
    fh.write(hdr + "/** Advance width per character, in em (1 = font size). */\n")
    fh.write("export type FicheFont = 'FicheSerif' | 'FicheSerifBold' | 'FicheSans';\n")
    fh.write("export const FICHE_METRICS: Record<FicheFont, Record<string, number>> = "
             + json.dumps(metrics, ensure_ascii=False) + ";\n")

logos_dir = sys.argv[1]
def png_uri(name, max_px):
    im = Image.open(os.path.join(logos_dir, name)).convert("RGBA")
    im.thumbnail((max_px, max_px))
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
with open(os.path.join(OUT, "defaultLogos.ts"), "w") as fh:
    fh.write(hdr + "// Logos extracted from the original ENNOUR fiche (native resolution ≈ 200 ppi).\n")
    fh.write(f"export const DEFAULT_LOGO_ARRU = {json.dumps(png_uri('arru.png', 400))};\n")
    fh.write(f"export const DEFAULT_LOGO_SAMED = {json.dumps(png_uri('samed.png', 400))};\n")
    fh.write(f"export const DEFAULT_LOGO_SOIT = {json.dumps(png_uri('soit.png', 400))};\n")
print("flavor", flavor)
